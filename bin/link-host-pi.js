"use strict";
/* eslint-disable @typescript-eslint/no-require-imports */

const fs = require("node:fs");
const path = require("node:path");
const { pathToFileURL } = require("node:url");
const { resolveHostPi } = require("./host-pi");

/**
 * Pi Web's sources import these packages by name. Node redirects those imports
 * to the validated host Pi through bin/host-pi-runtime.js, but TypeScript,
 * Turbopack and webpack resolve them through node_modules and never see that
 * hook. Turbopack compiles only files inside the workspace root, so the host
 * installation cannot be symlinked in; write small packages that re-export the
 * validated host entry instead.
 */
const SHIMMED_PACKAGES = [
  "@earendil-works/pi-coding-agent",
  "@earendil-works/pi-agent-core",
  "@earendil-works/pi-ai",
  "@earendil-works/pi-tui",
];

const GENERATED_BY = "// Generated by bin/link-host-pi.js. Do not edit.";

function typesSpecifier(descriptor, packageJson) {
  const declared = packageJson.exports?.["."]?.types ?? packageJson.types ?? packageJson.typings;
  if (typeof declared !== "string") return undefined;
  const declarations = path.resolve(descriptor.dir, declared);
  if (!fs.existsSync(declarations)) return undefined;
  return declarations.replace(/\.d\.ts$/, "").split(path.sep).join("/");
}

function shimFiles(name, descriptor) {
  const packageJson = JSON.parse(fs.readFileSync(path.join(descriptor.dir, "package.json"), "utf8"));
  const types = typesSpecifier(descriptor, packageJson);
  const files = {
    "package.json": `${JSON.stringify({
      name,
      version: packageJson.version,
      private: true,
      type: "module",
      exports: { ".": { ...(types ? { types: "./index.d.ts" } : {}), import: "./index.js" } },
    }, null, 2)}\n`,
    // `export *` omits a default binding; no Pi package exports one, and Pi Web
    // imports only named values and types from the package root.
    "index.js": `${GENERATED_BY}\nexport * from ${JSON.stringify(pathToFileURL(descriptor.entry).href)};\n`,
  };
  if (types) {
    files["index.d.ts"] = `${GENERATED_BY}\nexport * from ${JSON.stringify(types)};\n`;
  }
  return files;
}

function writeHostPiShims(runtime, checkoutDir = path.join(__dirname, "..")) {
  // Read the host packages before touching the checkout, so an incomplete
  // runtime cannot leave a half-written node_modules behind.
  const shims = SHIMMED_PACKAGES.map((name) => {
    const descriptor = runtime.packages[name];
    if (!descriptor) throw new Error(`Validated host Pi runtime is missing ${name}`);
    return {
      dir: path.join(checkoutDir, "node_modules", ...name.split("/")),
      files: shimFiles(name, descriptor),
    };
  });

  for (const { dir, files } of shims) {
    fs.rmSync(dir, { recursive: true, force: true });
    fs.mkdirSync(dir, { recursive: true });
    for (const [file, content] of Object.entries(files)) {
      fs.writeFileSync(path.join(dir, file), content);
    }
  }
  return shims.map((shim) => shim.dir);
}

if (require.main === module) {
  try {
    writeHostPiShims(resolveHostPi());
  } catch (error) {
    // Installing without a host Pi is allowed; development, build, type-check
    // and tests report the same failure when they need the packages.
    console.warn(`[pi-web] ${error instanceof Error ? error.message : String(error)}`);
  }
}

module.exports = { SHIMMED_PACKAGES, writeHostPiShims };
